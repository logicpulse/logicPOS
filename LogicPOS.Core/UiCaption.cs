using System.Text.RegularExpressions;

namespace LogicPOS.Core;

/// <summary>
/// Portuguese UI captions that are still written in code or XAML, shown in English
/// when <see cref="UiCulture"/> is en-US or en-GB. Other cultures keep Portuguese.
/// </summary>
public static class UiCaption
{
    private const string NextStepPt = "Próximo passo recomendado: ";
    private const string NextStepEn = "Recommended next step: ";

    private static readonly Regex RequiredStepsPt = new(
        @"^(?<done>\d+) de (?<total>\d+) passos obrigatórios concluídos$",
        RegexOptions.CultureInvariant | RegexOptions.Compiled);

    private static readonly Regex RequiredStepsEn = new(
        @"^(?<done>\d+) of (?<total>\d+) required steps completed$",
        RegexOptions.CultureInvariant | RegexOptions.Compiled);

    private static readonly Regex BulkArticlesPt = new(
        @"^Vai alterar (?<count>\d+) artigo\(s\) selecionado\(s\)\. Só os campos marcados com «Alterar» são gravados\.$",
        RegexOptions.CultureInvariant | RegexOptions.Compiled);

    private static readonly Regex BulkArticlesEn = new(
        @"^This will change (?<count>\d+) selected article\(s\)\. Only fields ticked with “Change” are saved\.$",
        RegexOptions.CultureInvariant | RegexOptions.Compiled);

    private static readonly Dictionary<string, string> ToEnglish = new(StringComparer.Ordinal);
    private static readonly Dictionary<string, string> ToPortuguese = new(StringComparer.Ordinal);

    static UiCaption()
    {
        foreach (var (portuguese, english) in Pairs)
        {
            if (string.Equals(portuguese, english, StringComparison.Ordinal))
            {
                continue;
            }

            ToEnglish.TryAdd(portuguese, english);
            ToPortuguese.TryAdd(english, portuguese);
        }
    }

    public static bool IsEnglish
    {
        get
        {
            var name = UiCulture.Read(null);
            return name.StartsWith("en", StringComparison.OrdinalIgnoreCase);
        }
    }

    /// <summary>Portuguese to English while the UI culture is English. Other cultures are left unchanged.</summary>
    public static string Display(string? text)
    {
        if (string.IsNullOrEmpty(text) || IsEnglish == false)
        {
            return text ?? string.Empty;
        }

        if (ToEnglish.TryGetValue(text, out var english))
        {
            return english;
        }

        if (text.StartsWith(NextStepPt, StringComparison.Ordinal))
        {
            return NextStepEn + Display(text[NextStepPt.Length..]);
        }

        var steps = RequiredStepsPt.Match(text);
        if (steps.Success)
        {
            return $"{steps.Groups["done"].Value} of {steps.Groups["total"].Value} required steps completed";
        }

        var bulk = BulkArticlesPt.Match(text);
        if (bulk.Success)
        {
            return $"This will change {bulk.Groups["count"].Value} selected article(s). Only fields ticked with “Change” are saved.";
        }

        return text;
    }

    /// <summary>English caption back to Portuguese. Used only when leaving English, before French or Spanish chrome is applied.</summary>
    public static string Revert(string? text)
    {
        if (string.IsNullOrEmpty(text))
        {
            return text ?? string.Empty;
        }

        if (ToPortuguese.TryGetValue(text, out var portuguese))
        {
            return portuguese;
        }

        if (text.StartsWith(NextStepEn, StringComparison.Ordinal))
        {
            return NextStepPt + Revert(text[NextStepEn.Length..]);
        }

        var stepsEn = RequiredStepsEn.Match(text);
        if (stepsEn.Success)
        {
            return $"{stepsEn.Groups["done"].Value} de {stepsEn.Groups["total"].Value} passos obrigatórios concluídos";
        }

        var bulkEn = BulkArticlesEn.Match(text);
        if (bulkEn.Success)
        {
            return $"Vai alterar {bulkEn.Groups["count"].Value} artigo(s) selecionado(s). Só os campos marcados com «Alterar» são gravados.";
        }

        return text;
    }

    /// <summary>Display while English, otherwise the Portuguese caption when the text is one we translated.</summary>
    public static string ForUi(string? text) => IsEnglish ? Display(text) : Revert(text);

